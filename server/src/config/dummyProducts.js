/**
 * Returns a cloned array of dummy products prepared for a given tenant ID
 * @param {string|object} tenantId 
 * @returns {Array} Array of product documents ready for insertion
 */
const getDummyProducts = (tenantId) => {
  const tId = tenantId ? tenantId.toString() : 'tenant_1';
  return DUMMY_PRODUCTS_TEMPLATE.map((p, index) => ({
    _id: `prod_seed_${Date.now()}_${index}`,
    tenantId: tId,
    title: p.title,
    sku: p.sku,
    category: p.category,
    price: p.price,
    sellingPrice: p.price,
    costPrice: p.costPrice,
    stockQuantity: p.stockQuantity,
    lowStockAlert: p.lowStockAlert,
    lowStockThreshold: p.lowStockAlert,
    image: p.image,
    imageUrl: p.image,
    unitType: p.unitType || 'piece',
    allowFractional: false,
    description: p.description,
    variants: Array.isArray(p.variants) ? p.variants : [],
    status: 'active',
    createdAt: new Date(),
    updatedAt: new Date(),
  }));
};

